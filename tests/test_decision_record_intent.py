_TARGET = "def magnitude(x):\n    if x >= 0:\n        return x\n    return -x\n"
_SUITE = (
    "from mod import magnitude\n\n\ndef test_magnitude():\n    assert magnitude(3) == 3\n"
    "    assert magnitude(-2) == 2\n"
)
_PYPROJECT = (
    '[tool.pytest.ini_options]\npythonpath = ["."]\nmarkers = ["detective: tests generated by Detective"]\n'
)
_FN = "p.py::quote"


def _project(root) -> str:
    """A fresh project: one function, one test that leaves an equivalent survivor, a clean regime."""
    os.makedirs(root, exist_ok=True)
    for name, text in (("mod.py", _TARGET), ("test_mod.py", _SUITE), ("pyproject.toml", _PYPROJECT)):
        with open(os.path.join(root, name), "w", encoding="utf-8") as fh:
            fh.write(text)
    return str(root)


def _cli(root: str, *argv: str) -> subprocess.CompletedProcess:
    """The real command, in its own process — the surface a harness actually reads."""
    return subprocess.run(
        [sys.executable, "-m", "Detective", *argv, "--project-root", root],
        capture_output=True,
        text=True,
        cwd=root,
        check=False,
    )


def _command_in(line: str) -> list[str]:
    """The Detective command a printed line names, as tokens after `detective` — `shlex.split` of the
    command, its trailing shell comment dropped."""
    tokens = shlex.split(line[line.index("detective ") :], comments=True)
    assert tokens[0] == "detective"
    return tokens[1:]


def _first(out: list[str], prefix: str) -> str:
    return next(line for line in out if line.startswith(prefix))


