"""Intent tests for the decision record (`docs/theory/COMMUNICATING_DETERMINISM.md` §9.8).

THE DEFECT: the decision reached only the printed page, and a `--json` run recorded no outcome in the
ledger. Detective already computed every next action as typed data — `converge_next_action`,
`audit_next_action`, `regime_outcome` — in pinned pure functions, and handed it only to the page:
`--json` carried the raw result and never the decision, so a harness reading the machine channel had to
re-derive what the page routes on — a second reading of the same facts, "drift with a delay fuse". And
the outcome reached the ledger only from inside the page's renderer, so `converge --json`,
`audit --json`, `converge --full` and converge's stale and cut endings recorded none.

These pin the repair from intent, not from the code that implements it:

* every `--json` payload of converge, audit and regime carries `decision`, whose code is the code that
  verb's page routed on — and every field the payload carried before it is still there;
* for every kind of move, the command the page prints and the record's `argv` / `then` are ONE command;
* a `--json` converge and a `--json` audit each record exactly one outcome, and so do the stale and cut
  endings that print before converge's action block;
* `doctor --json` and `flag --json` parse and carry their codes, and an unread doctor axis never reads
  as a clean one;
* a hand-pin item carries the test Detective writes itself, which compiles — and null where Detective
  declines, exactly as converge declines.
"""

