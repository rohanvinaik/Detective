def _args(root, **overrides) -> types.SimpleNamespace:
    """The namespace `converge`'s parser builds, for a run with no supplied input."""
    base = dict(
        input=None,
        project_root=str(root),
        env=None,
        write_dir="tests/detective",
        max_iterations=3,
        clock=None,
        receiver_factory=None,
        fast=False,
        deadline=300.0,
        include_shaped=False,
        two_sign=False,
        isolated=False,
        json=False,
        full=False,
        verbose=False,
    )
    base.update(overrides)
    return types.SimpleNamespace(**base)


def _converge_returns(monkeypatch, result: ConvergeResult) -> None:
    """Make the engine call `_run_converge` makes return ``result``. The MODULE is patched: on the
    package, `Detective.converge` is the re-exported function, and the handler imports from the module."""
    monkeypatch.setattr(importlib.import_module("Detective.converge"), "converge", lambda *_a, **_k: result)


def _unfinished(**overrides) -> ConvergeResult:
    return ConvergeResult(
        "m.py::add",
        False,
        False,
        1,
        1,
        (),
        None,
        line_complete=False,
        missing_lines=(3,),
        signature="add(a, b)",
        param_names=("a", "b"),
        **overrides,
    )


@pytest.mark.parametrize(
    ("overrides", "code", "ending"),
    [
        ({"stale_target": True}, "rerun_stale", "⚠ stale"),
        # A cut no profile flagged: the result carries no cut reason, its standing reads `incomplete`,
        # and `converge_next_action` alone would say close_the_gap under a page that says "re-run with
        # a larger wall".
        ({"budget_exhausted": True, "cut_phase": "classification"}, "repair_measurement", "⚠ CUT"),
    ],
)
def test_the_stale_and_cut_endings_record_their_outcome(
    monkeypatch, tmp_path, capsys, overrides, code, ending
):
    _converge_returns(monkeypatch, _unfinished(**overrides))
    reset_observations()
    _run_converge(_args(tmp_path), "m.py", "add")
    assert ending in capsys.readouterr().out, "the ending prints the text it always printed"
    assert take_observations() == (("outcome", "converge", code),)


def test_a_full_converge_records_its_outcome_too(monkeypatch, tmp_path, capsys):
    _converge_returns(monkeypatch, _unfinished())
    reset_observations()
    _run_converge(_args(tmp_path, full=True), "m.py", "add")
    capsys.readouterr()
    assert take_observations() == (("outcome", "converge", "close_the_gap"),)


def test_the_cut_endings_record_names_the_remedy_its_reasons_route_to(monkeypatch, tmp_path, capsys):
    _converge_returns(monkeypatch, _unfinished(budget_exhausted=True, cut_phase="classification"))
    _run_converge(_args(tmp_path, json=True), "m.py", "add")
    decision = json.loads(capsys.readouterr().out)["decision"]
    take_observations()
    assert (decision["code"], decision["route"]) == ("repair_measurement", "deadline")
    assert decision["step"] == {
        "kind": "run",
        "argv": ["converge", "m.py::add", "--deadline", "0"],
        "then": None,
        "remedy": "",
    }


