_DOCTOR_GREEN = {
    "regime_conflict",
    "no_pytest",
    "deps_elsewhere",
    "deps_missing",
    "stale_load_failure",
    "stale_collection_failure",
    "clean",
}
_DOCTOR_RED = {"ground_moved", "spiral", "order", "repeat_no_change", "clear", "unavailable"}
_DOCTOR_YELLOW = {
    "extractable_core",
    "impure_body",
    "trapped_by_imports",
    "unresolved_param",
    "clear",
    "nothing_to_read",
}
_DOCTOR_MIX = {"none", "suppression", "unreliability", "ordering", "ordered_remediation"}


def test_doctor_json_parses_and_carries_each_axis_code(tmp_path, capsys):
    (tmp_path / "m.py").write_text("def add(a, b):\n    return a + b\n")
    status = main(["doctor", "m.py", "--project-root", str(tmp_path), "--json"])
    payload = json.loads(capsys.readouterr().out)
    assert payload["exit_code"] == status
    assert (payload["target"], payload["asked"]) == ("m.py", ["green", "red", "yellow"])
    assert payload["green"]["code"] in _DOCTOR_GREEN
    assert isinstance(payload["green"]["facts"], dict)
    assert payload["red"]["code"] in _DOCTOR_RED
    assert isinstance(payload["red"]["facts"], dict)
    assert payload["yellow"]["code"] in _DOCTOR_YELLOW
    assert isinstance(payload["yellow"]["findings"], list)
    assert payload["mix"] in _DOCTOR_MIX
    # doctor's observation stays, on the JSON branch too
    codes = f"{payload['green']['code']}/{payload['yellow']['code']}"
    assert read_recent(str(tmp_path))[-1]["outcome"] == [["outcome", "doctor", codes]]


def test_doctor_json_never_reports_an_unread_axis_as_clean(tmp_path, capsys):
    (tmp_path / "m.py").write_text("def add(a, b):\n    return a + b\n")
    main(["doctor", "m.py", "--green", "--project-root", str(tmp_path), "--json"])
    partial = json.loads(capsys.readouterr().out)
    assert partial["asked"] == ["green"]
    assert (partial["red"]["code"], partial["yellow"]["code"]) == ("not_read", "not_read")
    main(["doctor", "--project-root", str(tmp_path), "--json"])
    untargeted = json.loads(capsys.readouterr().out)
    assert untargeted["yellow"]["code"] == "not_read", "taste with no target was not read — never `clear`"


def test_flag_json_refuses_with_the_survivors_and_records_with_its_flag(tmp_path):
    root = _project(tmp_path / "flagged")
    refused = _cli(root, "flag", "mod.py::magnitude", "NOT_A_MUTANT", "--json")
