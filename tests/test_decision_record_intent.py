def _hand_pin_result(function: str, signature: str) -> types.SimpleNamespace:
    return _gap_result(function=function, signature=signature, param_names=("x",))


def test_a_hand_pin_item_carries_detectives_own_test_which_compiles(tmp_path):
    (tmp_path / "decision_hand_pin.py").write_text(
        "def check(x):\n    if x < 0:\n        raise ValueError('bad')\n    return x\n"
    )
    result = _hand_pin_result("decision_hand_pin.py::check", "check(x)")
    rep = SurvivorReport(
        verdicts=(
            _verdict(Witness(args=(-1,), original="<raised ValueError: bad>", mutant="-1"), "VALUE_0000000a"),
        ),
        unclassified=(),
    )
    d = _converge_decision(result, rep, str(tmp_path))
