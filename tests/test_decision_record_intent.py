def test_doctor_json_parses_and_carries_each_axis_code(tmp_path, capsys):
    (tmp_path / "m.py").write_text("def add(a, b):\n    return a + b\n")
    status = main(["doctor", "m.py", "--project-root", str(tmp_path), "--json"])
    payload = json.loads(capsys.readouterr().out)
    assert payload["exit_code"] == status
    assert (payload["target"], payload["asked"]) == ("m.py", ["green", "red", "yellow"])
    assert payload["green"]["code"] in _DOCTOR_GREEN
    assert isinstance(payload["green"]["facts"], dict)
    assert payload["red"]["code"] in _DOCTOR_RED
