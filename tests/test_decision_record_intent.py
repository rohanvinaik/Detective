@pytest.fixture(scope="module")
def walk(tmp_path_factory):
    """One walk per channel, each in its own fresh project — regime, converge, audit — with `--json` on
    one side and the printed page on the other. The inputs are identical, so the outcome the page side
    recorded for each verb IS the code that verb's page routed on."""
    machine = _project(tmp_path_factory.mktemp("json_side"))
    page = _project(tmp_path_factory.mktemp("page_side"))
    walked: dict = {"json": {}, "page": {}}
    for verb, argv in (
        ("regime", ("regime",)),
        ("converge", ("converge", "mod.py::magnitude")),
        ("audit", ("audit", "mod.py::magnitude")),
    ):
        proc = _cli(machine, *argv, "--json")
        walked["json"][verb] = (proc.returncode, json.loads(proc.stdout))
        walked["page"][verb] = _cli(page, *argv).stdout
    walked["json_rows"] = read_recent(machine)
    walked["page_rows"] = read_recent(page)
    return walked


def test_each_verbs_json_carries_the_code_its_page_routed_on(walk):
    page_outcomes = {row["verb"]: row["outcome"] for row in walk["page_rows"]}
    for verb in ("regime", "converge", "audit"):
        status, payload = walk["json"][verb]
        decision = payload["decision"]
        assert decision["verb"] == verb
        assert page_outcomes[verb] == [["outcome", verb, decision["code"]]], verb
        assert payload["exit_code"] == status


def test_the_decision_sits_beside_every_field_the_payload_carried_before(walk):
    """`decision` is ADDED: nothing the payload carried is renamed, moved or dropped."""
    added = {"decision", "exit_code", "exit_meaning"}
    assert set(walk["json"]["converge"][1]) - added == {f.name for f in fields(ConvergeResult)}
    assert set(walk["json"]["audit"][1]) - added == {f.name for f in fields(SuiteAudit)}
    assert set(walk["json"]["regime"][1]) - added == {"regime", "applied"}


def test_the_record_carries_the_decided_state_each_verb_holds(walk):
    assert set(walk["json"]["converge"][1]["decision"]["state"]) == {
        "standing",
        "killable",
        "candidate_equivalent",
        "crash_only",
    }
    assert set(walk["json"]["audit"][1]["decision"]["state"]) == {"headline"}
    assert set(walk["json"]["regime"][1]["decision"]["state"]) == {"blocked", "needed"}


def test_a_json_converge_and_a_json_audit_each_record_exactly_one_outcome(walk):
    recorded = {row["verb"]: row["outcome"] for row in walk["json_rows"]}
    for verb in ("converge", "audit"):
        assert recorded[verb] == [["outcome", verb, walk["json"][verb][1]["decision"]["code"]]], verb


def test_a_settled_converges_record_names_what_its_done_block_prints(walk):
    """DONE runs nothing; its residual and its NEXT commands are what the page prints from."""
    decision = walk["json"]["converge"][1]["decision"]
    page = walk["page"]["converge"].splitlines()
    assert decision["code"] == "settled"
    assert (decision["step"]["kind"], decision["step"]["argv"], decision["step"]["then"]) == (
        "done",
        None,
        None,
    )
    printed_next = [
        _command_in(line) for line in page if line.strip().startswith("detective ") and "<" not in line
    ]
    assert printed_next == decision["optional"]
    flag_line = next(line for line in page if "detective flag" in line)
    assert _command_in(flag_line)[2] == decision["residual"]["flaggable_ids"][0]
    assert not any(token.startswith("<") for command in decision["optional"] for token in command), (
        "a placeholder is never a command"
    )


