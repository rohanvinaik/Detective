def _write_synth(tmp_path, name, owner, tests):
    body = "\n\n".join(f"def {t}():\n    pass" for t in tests)
    (tmp_path / name).write_text(
        f'"""Auto-generated by Detective — warrant-classed tests for {owner}."""\n\n{body}\n'
    )


def test_foreign_names_exclude_own_file_and_user_files(tmp_path):
    _write_synth(tmp_path, "test_alpha_synth.py", "src/a.py::alpha", ["test_alpha_value_0"])
    _write_synth(tmp_path, "test_beta_synth.py", "src/b.py::beta", ["test_beta_value_0", "test_beta_golden"])
    # a user file matching the name pattern but WITHOUT the header is not generated
    (tmp_path / "test_gamma_synth.py").write_text("def test_gamma_handwritten():\n    pass\n")
    foreign = foreign_generated_test_names(str(tmp_path), "src/a.py::alpha")
    assert foreign == {"test_beta_value_0", "test_beta_golden"}


def test_foreign_scan_skips_hidden_and_cache_dirs(tmp_path):
    hidden = tmp_path / ".venv"
    hidden.mkdir()
    _write_synth(hidden, "test_zeta_synth.py", "z.py::zeta", ["test_zeta_value_0"])
    assert foreign_generated_test_names(str(tmp_path), "a.py::alpha") == set()


def test_colliding_bare_name_is_not_stripped_from_own_evidence(tmp_path):
    # Review finding 6: a.py::validate and b.py::validate both emit
    # test_validate_value_0 — one bare-name column in the matrix. The own file
    # defines it, so it survives sibling rewrites: durable, never stripped.
    _write_synth(tmp_path, "test_validate_synth.py", "a.py::validate", ["test_validate_value_0"])
    (tmp_path / "sub").mkdir()
    _write_synth(
        tmp_path / "sub",
        "test_validate_synth.py",
        "b.py::validate",
        ["test_validate_value_0", "test_validate_golden"],
    )
    foreign = foreign_generated_test_names(str(tmp_path), "a.py::validate")
    assert "test_validate_value_0" not in foreign
    assert "test_validate_golden" in foreign


def _prop(assertion: str, golden: tuple[str, str] | None = None) -> ExecutableProperty:
    return ExecutableProperty(
        category="VALUE",
        inputs={},
        setup_code="",
        assertion_code=assertion,
        preconditions=[],
        confidence=0.9,
        golden_case=golden,
    )


def test_golden_row_properties_maps_rows_in_render_order():
    # Issue #13: `test_x_golden[args<K>-…]` row K must map to the K-th golden here
    golden_a = _prop("assert f(1) == 'a=5'", ("(1,)", "'a=5'"))
    golden_b = _prop("assert f(2) == 'b=6'", ("(2,)", "'b=6'"))
    witness = _prop("assert f(3) == 9")
    base, rows = golden_row_properties("m.py::f", [golden_a, witness, golden_b])
    assert base == "test_f_golden"
    assert rows == [golden_a, golden_b]  # props order, witnesses excluded


def test_golden_row_properties_empty_below_the_parametrize_fold():
    # 0 or 1 golden renders individually — no parametrized rows exist to map
    single = _prop("assert f(1) == 'a'", ("(1,)", "'a'"))
    _, rows = golden_row_properties("m.py::f", [single])
    assert rows == []
